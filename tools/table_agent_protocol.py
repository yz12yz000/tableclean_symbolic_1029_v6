"""Small, ROS-free protocol checks for the optional table Agent boundary.

The Agent is allowed to describe intent and reference objects from one fresh
observation. It is never allowed to submit robot coordinates, poses, scripts,
or trajectories.  The runner remains the source of truth for all geometry.
"""

from copy import deepcopy
import hashlib
import json
import math
from numbers import Real
import re


SCHEMA_VERSION = 1
TASK_TYPE = "clear_table"
RUNNER_PROTOCOL_VERSION = "table-runner-v1"
RUNNER_REVISION = "table-clean-runner-v2"
WORKSPACE_REVISION = "release:table-clean-v1"
_MAX_TEXT = 256
_MAX_LIST = 256
_UUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$")
_HEX64_RE = re.compile(r"^[0-9a-fA-F]{64}$")


def _fail(reason):
    raise ValueError("invalid_table_agent:" + reason)


def _keys(value, required, optional=()):
    if type(value) is not dict:
        _fail("object")
    keys = set(value)
    if not set(required) <= keys or keys - set(required) - set(optional):
        _fail("fields")


def _text(value, name, *, empty=False):
    if type(value) is not str or len(value) > _MAX_TEXT:
        _fail(name)
    if not empty and (not value or value != value.strip() or any(c.isspace() for c in value)):
        _fail(name)
    return value


def _positive_int(value, name, *, minimum=1, maximum=1000000):
    if type(value) is not int or not minimum <= value <= maximum:
        _fail(name)
    return value


def _finite(value, name, *, positive=False, nonnegative=False, maximum=None):
    if isinstance(value, bool) or not isinstance(value, Real) or not math.isfinite(value):
        _fail(name)
    if positive and value <= 0:
        _fail(name)
    if nonnegative and value < 0:
        _fail(name)
    if maximum is not None and value > maximum:
        _fail(name)
    return float(value)


def _json_safe(value, depth=0):
    if depth > 10:
        _fail("nesting")
    if value is None or type(value) is bool or type(value) is str:
        return
    if type(value) in (int, float):
        if isinstance(value, float) and not math.isfinite(value):
            _fail("nonfinite")
        return
    if type(value) is list:
        if len(value) > _MAX_LIST:
            _fail("list_limit")
        for item in value:
            _json_safe(item, depth + 1)
        return
    if type(value) is dict:
        if len(value) > _MAX_LIST:
            _fail("object_limit")
        for key, item in value.items():
            if type(key) is not str:
                _fail("json_key")
            _json_safe(item, depth + 1)
        return
    _fail("json_value")


def _copy(value):
    _json_safe(value)
    try:
        return json.loads(json.dumps(value, ensure_ascii=False, allow_nan=False,
                                    sort_keys=True, separators=(",", ":")))
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError("invalid_table_agent:json") from exc


def validate_task_policy(value, *, expected_mode=None, require_deployment_metadata=False,
                         expected_workspace_revision=None):
    """Validate the high-level policy generated by an external Agent.

    v1 intentionally supports only all bowls.  Adding a selector without a
    corresponding, measured field in the vision state would make a plan look
    accepted while silently selecting the wrong object.
    """
    _keys(value, {"schema_version", "plan_id", "task_type", "selector", "priority", "limits", "mode"},
          {"runner_protocol_version", "workspace_revision", "model", "reason"})
    if type(value["schema_version"]) is not int or value["schema_version"] != SCHEMA_VERSION:
        _fail("schema_version")
    _text(value["plan_id"], "plan_id")
    if require_deployment_metadata and not _UUID_RE.fullmatch(value["plan_id"]):
        _fail("plan_id")
    if value["task_type"] != TASK_TYPE:
        _fail("task_type")
    selector = value["selector"]
    _keys(selector, {"kind"}, {"attributes"})
    if selector["kind"] != "all_bowls":
        _fail("selector_unsupported")
    if "attributes" in selector:
        if type(selector["attributes"]) is not dict or selector["attributes"]:
            _fail("selector_attributes_unsupported")
    priority = value["priority"]
    _keys(priority, {"order", "regions"})
    if priority["order"] not in ("largest_first", "distance_first"):
        _fail("priority_order")
    if type(priority["regions"]) is not list or len(priority["regions"]) > _MAX_LIST:
        _fail("priority_regions")
    if priority["regions"]:
        _fail("priority_regions_unsupported")
    for region in priority["regions"]:
        _text(region, "priority_region")
    limits = value["limits"]
    _keys(limits, {"max_observation_rounds", "max_replans", "deadline_s"},
          {"max_reobservations", "max_completed_objects"})
    _positive_int(limits["max_observation_rounds"], "max_observation_rounds", maximum=10000)
    _positive_int(limits["max_replans"], "max_replans", maximum=10000)
    _finite(limits["deadline_s"], "deadline_s", positive=True, maximum=86400)
    if "max_reobservations" in limits:
        _positive_int(limits["max_reobservations"], "max_reobservations", minimum=0, maximum=10000)
    if "max_completed_objects" in limits:
        _positive_int(limits["max_completed_objects"], "max_completed_objects", maximum=10000)
    if value["mode"] not in ("preview", "execute"):
        _fail("mode")
    if expected_mode is not None and value["mode"] != expected_mode:
        _fail("mode_mismatch")
    if "runner_protocol_version" in value:
        _text(value["runner_protocol_version"], "runner_protocol_version")
        if value["runner_protocol_version"] != RUNNER_PROTOCOL_VERSION:
            _fail("runner_protocol_version")
    elif require_deployment_metadata:
        _fail("runner_protocol_version_missing")
    if "workspace_revision" in value:
        _text(value["workspace_revision"], "workspace_revision")
        if "/" in value["workspace_revision"] or "\\" in value["workspace_revision"]:
            _fail("workspace_revision_path")
        if (expected_workspace_revision is not None
                and value["workspace_revision"] != expected_workspace_revision):
            _fail("workspace_revision_mismatch")
    elif require_deployment_metadata:
        _fail("workspace_revision_missing")
    if "model" in value:
        model = value["model"]
        _keys(model, {"provider", "model", "plan_hash"})
        _text(model["provider"], "model.provider")
        _text(model["model"], "model.model")
        _text(model["plan_hash"], "model.plan_hash")
        if require_deployment_metadata:
            if not _HEX64_RE.fullmatch(model["plan_hash"]):
                _fail("model.plan_hash")
            if model["plan_hash"].lower() != policy_hash(value):
                _fail("model.plan_hash_mismatch")
    elif require_deployment_metadata:
        _fail("model_missing")
    if "reason" in value and (type(value["reason"]) is not str or len(value["reason"]) > _MAX_TEXT):
        _fail("reason")
    return _copy(value)


def validate_round_decision(value, *, task_id=None, plan_id=None, observation_id=None,
                            scene_revision=None):
    """Validate a low-level selection without accepting any geometry."""
    _keys(value, {"schema_version", "plan_id", "task_id", "observation_id",
                  "scene_revision", "selection"}, {"reason", "fallback_order"})
    if type(value["schema_version"]) is not int or value["schema_version"] != SCHEMA_VERSION:
        _fail("schema_version")
    for name, expected in (("plan_id", plan_id), ("task_id", task_id),
                           ("observation_id", observation_id), ("scene_revision", scene_revision)):
        _text(value[name], name)
        if expected is not None and value[name] != expected:
            _fail(name + "_mismatch")
    selection = value["selection"]
    _keys(selection, {"object_id", "candidate_id", "slot_id"})
    _positive_int(selection["object_id"], "selection.object_id", minimum=0, maximum=2**32 - 1)
    _positive_int(selection["candidate_id"], "selection.candidate_id", minimum=0, maximum=32)
    _text(selection["slot_id"], "selection.slot_id")
    if "reason" in value and (type(value["reason"]) is not str or len(value["reason"]) > _MAX_TEXT):
        _fail("reason")
    if "fallback_order" in value:
        fallbacks = value["fallback_order"]
        if type(fallbacks) is not list or len(fallbacks) > 32:
            _fail("fallback_order")
        if fallbacks:
            _fail("fallback_order_unsupported")
        for item in fallbacks:
            _keys(item, {"object_id", "candidate_id", "slot_id"})
            _positive_int(item["object_id"], "fallback.object_id", minimum=0, maximum=2**32 - 1)
            _positive_int(item["candidate_id"], "fallback.candidate_id", minimum=0, maximum=32)
            _text(item["slot_id"], "fallback.slot_id")
    return _copy(value)


def scene_revision(value):
    """Return a deterministic digest for an immutable scene/policy payload."""
    copied = _copy(value)
    encoded = json.dumps(copied, ensure_ascii=False, sort_keys=True,
                         separators=(",", ":"), allow_nan=False).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def canonical_json(value):
    """Encode validated JSON-shaped data for hashing or atomic persistence."""
    return json.dumps(_copy(value), ensure_ascii=False, sort_keys=True,
                      separators=(",", ":"), allow_nan=False)


def policy_hash(value):
    """Hash a policy while omitting its self-referential model.plan_hash."""
    copied = _copy(value)
    model = copied.get("model")
    if isinstance(model, dict) and "plan_hash" in model:
        model = dict(model)
        model.pop("plan_hash")
        copied["model"] = model
    return hashlib.sha256(canonical_json(copied).encode("utf-8")).hexdigest()


def load_agent_json(path):
    """Reject ambiguous duplicate keys before policy/result validation."""
    def unique_keys(pairs):
        value = {}
        for key, item in pairs:
            if key in value:
                _fail("duplicate_key")
            value[key] = item
        return value

    with open(path, encoding="utf-8") as stream:
        return json.load(stream, object_pairs_hook=unique_keys)


def validate_execution_baseline(policy, baseline_policy, baseline, preflight):
    """Check the preview evidence before any live ROS/controller activity."""
    validate_task_policy(policy, expected_mode="execute", require_deployment_metadata=True,
                         expected_workspace_revision=WORKSPACE_REVISION)
    validate_task_policy(baseline_policy, expected_mode="preview", require_deployment_metadata=True,
                         expected_workspace_revision=WORKSPACE_REVISION)
    if policy["plan_id"] == baseline_policy["plan_id"]:
        _fail("baseline_requires_new_plan_id")
    for key in ("task_type", "selector", "priority", "limits",
                "runner_protocol_version", "workspace_revision"):
        if policy[key] != baseline_policy[key]:
            _fail("baseline_policy_changed:" + key)
    if not isinstance(baseline, dict) or baseline.get("plan_id") != baseline_policy["plan_id"]:
        _fail("baseline_plan_id_mismatch")
    if (baseline.get("passed") is not True or baseline.get("mode") != "plan_only"
            or baseline.get("outcome") != "planned"
            or baseline.get("selection") != "clear_table"
            or baseline.get("hardware_motion_requested") is not False
            or baseline.get("simulated", False)):
        _fail("baseline_requires_successful_online_preview")
    previous = baseline.get("preflight")
    if not isinstance(previous, dict) or previous.get("policy_hash") != policy_hash(baseline_policy):
        _fail("baseline_policy_hash_mismatch")
    for key in ("runner_protocol_version", "runner_revision", "workspace_revision",
                "config_digest", "model_digest"):
        if previous.get(key) != preflight[key]:
            _fail("baseline_preflight_changed:" + key)
    return True
